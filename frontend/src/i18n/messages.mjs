export function normalizeLocale(value) { return value === 'en' ? 'en' : 'ko' }

export function translate(message, locale = 'ko', params = {}) {
  const text = locale === 'en' ? english[message] || message : message
  return text.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(params, key) ? String(params[key]) : match)
}
